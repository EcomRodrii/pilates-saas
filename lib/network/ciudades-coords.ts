function normalizarCiudad(ciudad: string): string {
  return ciudad
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '') // quita acentos
    .trim().toLowerCase();
}

/** `null` si la ciudad no está en la lista — nunca se inventa una posición. */
export function coordsDeCiudad(ciudad: string | null): { lat: number; lng: number } | null {
  if (!ciudad) return null;
  return CIUDADES_COORDS[normalizarCiudad(ciudad)] ?? null;
}
